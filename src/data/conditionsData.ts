export const getSubconditionsForService = (serviceId: string): SubConditionItem[] => {
  const normalized = serviceId.toLowerCase().trim();
  if (normalized.includes('neuro') && normalized.includes('rehab')) {
    return ALL_NEURO_REHAB_PROGRAMS;
  }
  if (normalized.includes('geriatric') || normalized.includes('elder') || normalized.includes('senior')) {
    return ALL_GERIATRIC_CONDITIONS;
  }
  if (normalized.includes('pediatric') || normalized.includes('child')) {
    return ALL_PEDIATRIC_CONDITIONS;
  }
  if (normalized.includes('sports')) {
    return ALL_SPORTS_INJURIES;
  }
  if (normalized.includes('neuro') && !normalized.includes('rehab')) {
    return ALL_NEUROLOGICAL_CONDITIONS;
  }
  if (normalized.includes('ortho')) {
    return ALL_ORTHOPEDIC_CONDITIONS;
  }
  return ALL_SUBCONDITIONS_BY_SERVICE[normalized] || [];
};

export const getAllSubconditions = (): SubConditionItem[] => {
  return [
    ...ALL_ORTHOPEDIC_CONDITIONS,
    ...ALL_NEUROLOGICAL_CONDITIONS,
    ...ALL_SPORTS_INJURIES,
    ...ALL_PEDIATRIC_CONDITIONS,
    ...ALL_GERIATRIC_CONDITIONS,
    ...ALL_NEURO_REHAB_PROGRAMS
  ];
};

export const getSubconditionById = (conditionId: string): SubConditionItem | undefined => {
  const all = getAllSubconditions();
  return all.find((c) => c.id === conditionId);
};





